"""Generates the Android Auto Now Playing icons in res/drawable (FR 19).

Android Auto draws a media session custom action from a drawable and never
draws text on it, so every number shown on a button needs its own icon. Text
becomes outlines because a vector drawable cannot use fonts.

Keep SPEEDS and the intervals in step with `car_media_controls.dart`, then
run from packages/audiflow_app:

    uv run tool/generate_car_icons.py
"""

from __future__ import annotations

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

APP_DIR = Path(__file__).resolve().parent.parent
RES_DIR = APP_DIR / "android/app/src/main/res/drawable"
# Roboto ships with the Flutter SDK, so the script needs no font of its own.
FONT_DIR = APP_DIR.parent.parent / ".fvm/flutter_sdk/bin/cache/artifacts/material_fonts"

SPEEDS = ["1.0", "1.2", "1.5", "1.8", "2.0"]
SKIP_FORWARD_SECONDS = [10, 15, 30, 45, 60]
SKIP_BACKWARD_SECONDS = [10, 15, 30]

VIEWPORT = 24.0
# Android Auto shows these small. A condensed face leaves the digits as tall
# as the width allows, in the full-width speed text and inside the skip circle.
SPEED_TEXT_WIDTH = 23.0
# The skip number sits inside the arrow's circle (centre (12, 13), inner
# radius 6), low enough to clear the arrowhead that ends at y = 11.
SKIP_TEXT_HEIGHT = 5.4
SKIP_TEXT_CENTER_Y = 14.2

# Material Icons `forward`/`replay` arcs (Apache 2.0).
FORWARD_ARROW = (
    "M18,13c0,3.31 -2.69,6 -6,6s-6,-2.69 -6,-6 2.69,-6 6,-6v4l5,-5 -5,-5v4"
    "c-4.42,0 -8,3.58 -8,8s3.58,8 8,8 8,-3.58 8,-8h-2z"
)
REWIND_ARROW = (
    "M12,5V1L7,6l5,5V7c3.31,0 6,2.69 6,6s-2.69,6 -6,6 -6,-2.69 -6,-6H4"
    "c0,4.42 3.58,8 8,8s8,-3.58 8,-8 -3.58,-8 -8,-8z"
)
# Material Icons `speed` (Apache 2.0), shown for a speed set between the steps.
SPEEDOMETER = (
    "M20.38,8.57l-1.23,1.85a8,8 0 0,1 -0.22,7.58H5.07A8,8 0 0,1 15.58,6.85"
    "l1.85,-1.23A10,10 0 0,0 3.35,19a2,2 0 0,0 1.72,1h13.85a2,2 0 0,0 1.74,-1"
    " 10,10 0 0,0 -0.27,-10.44zM10.59,15.41a2,2 0 0,0 2.83,0l5.66,-8.49"
    " -8.49,5.66a2,2 0 0,0 0,2.83z"
)


def _fmt(value: float) -> str:
    return f"{value:.2f}".rstrip("0").rstrip(".")


def _text_path(font: TTFont, text: str, scale: float, x: float, baseline: float) -> str:
    """Outlines [text] with its left edge at [x], y flipped for the viewport."""
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    parts: list[str] = []
    pen_x = 0.0
    for char in text:
        glyph = glyph_set[cmap[ord(char)]]
        pen = SVGPathPen(glyph_set, ntos=_fmt)
        glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, x + pen_x * scale, baseline)))
        parts.append(pen.getCommands())
        pen_x += glyph.width
    return "".join(parts)


def _text_width(font: TTFont, text: str) -> float:
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    return sum(glyph_set[cmap[ord(c)]].width for c in text)


def _cap_height(font: TTFont) -> float:
    return float(font["OS/2"].sCapHeight)


def speed_icon(font: TTFont, label: str) -> list[str]:
    text = f"{label}x"
    scale = SPEED_TEXT_WIDTH / _text_width(font, text)
    baseline = VIEWPORT / 2 + _cap_height(font) * scale / 2
    x = (VIEWPORT - SPEED_TEXT_WIDTH) / 2
    return [_text_path(font, text, scale, x, baseline)]


def skip_icon(font: TTFont, arrow: str, seconds: int) -> list[str]:
    text = str(seconds)
    scale = SKIP_TEXT_HEIGHT / _cap_height(font)
    x = (VIEWPORT - _text_width(font, text) * scale) / 2
    baseline = SKIP_TEXT_CENTER_Y + SKIP_TEXT_HEIGHT / 2
    return [arrow, _text_path(font, text, scale, x, baseline)]


def write_drawable(name: str, paths: list[str]) -> None:
    body = "\n".join(
        f'    <path\n        android:fillColor="#FFFFFFFF"\n'
        f'        android:pathData="{path}" />'
        for path in paths
    )
    (RES_DIR / f"{name}.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/generate_car_icons.py. Do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        f'    android:viewportWidth="{_fmt(VIEWPORT)}"\n'
        f'    android:viewportHeight="{_fmt(VIEWPORT)}">\n'
        f"{body}\n"
        "</vector>\n"
    )


def main() -> None:
    condensed = TTFont(FONT_DIR / "RobotoCondensed-Bold.ttf")
    write_drawable("ic_car_speed", [SPEEDOMETER])
    for label in SPEEDS:
        write_drawable(
            f"ic_car_speed_{label.replace('.', '_')}", speed_icon(condensed, label)
        )
    for seconds in SKIP_FORWARD_SECONDS:
        write_drawable(
            f"ic_car_forward_{seconds}", skip_icon(condensed, FORWARD_ARROW, seconds)
        )
    for seconds in SKIP_BACKWARD_SECONDS:
        write_drawable(
            f"ic_car_rewind_{seconds}", skip_icon(condensed, REWIND_ARROW, seconds)
        )


if __name__ == "__main__":
    main()
